from pathlib import Path
import tempfile
import unittest

from agent_config_score.scanner import analyze


FORMATS = ("AGENTS.md", "CLAUDE.md", "GEMINI.md", ".cursorrules",
           ".github/copilot-instructions.md", ".cursor/rules/review.mdc")


class GeneratedPathTests(unittest.TestCase):
    def scan(self, text, filename="AGENTS.md"):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            source = root / filename
            source.parent.mkdir(parents=True, exist_ok=True)
            source.write_text(text, encoding="utf-8")
            return analyze(root)

    def dead(self, text, **kwargs):
        return [(f.line, f.message) for f in self.scan(text, **kwargs).findings if f.code == "dead-path"]

    def test_explicit_generated_output_is_not_required_before_build(self):
        text = (
            "- `docs/.vitepress/contributor-names.json` is generated by `pnpm docs:contributors`\n"
            "- `docs/guide/cli-generated.md` is generated from `packages/vitest/src/node/cli/cli-config.ts` (it carries no banner saying so)\n"
            "`docs/out.json` is regenerated by `make docs`.\n"
            "`docs/out.json` IS GENERATED BY `make docs`!\n"
            "`docs/out.json` is rewritten by `make docs`.\n"
        )
        for filename in FORMATS:
            with self.subTest(filename=filename):
                self.assertEqual(self.dead(text, filename=filename), [
                    (2, "Referenced path does not exist: packages/vitest/src/node/cli/cli-config.ts")])

    def test_generated_words_and_incomplete_clauses_do_not_hide_required_files(self):
        lines = ["Generated files: read `docs/missing.json`.",
                 "`docs/missing.json` is not generated by `make docs`.",
                 "`docs/missing.json` is generated by a script.",
                 "`docs/missing.json` is generated by `make docs` but must already exist.",
                 "`docs/missing.json` is generated by `make docs",
                 "`docs/missing.json` is generated.",
                 "`docs/missing.json` may be generated by `make docs`."]
        self.assertEqual([line for line, _ in self.dead("\n".join(lines))], list(range(1, len(lines) + 1)))

    def test_exemption_does_not_cross_lines_or_hide_other_references(self):
        self.assertEqual([line for line, _ in self.dead(
            "`docs/out.json`\nis generated by `make docs`.\n"
            "Read `src/missing.py`; `docs/out.json` is generated by `make docs`.\n")], [1, 3])

    def test_markdown_destinations_are_checked_even_when_described_as_generated(self):
        self.assertEqual(self.dead("[Output](docs/out.json) is generated by `make docs`.\n"),
                         [(1, "Referenced path does not exist: docs/out.json")])

    def test_generated_context_does_not_exempt_command_or_secret_checks(self):
        report = self.scan("`docs/out.json` is generated by `rm -rf cache`.\n"
                           "`docs/out.json` is generated by `make docs`.\n"
                           "TOKEN=ghp_" + "A" * 36 + "\n")
        self.assertFalse(any(f.code == "dead-path" for f in report.findings))
        self.assertTrue(any(f.code == "rm-rf" for f in report.findings))
        self.assertTrue(any(f.code == "github-token" for f in report.findings))


class DirectoryPathTests(unittest.TestCase):
    def scan(self, text, directories=(), files=(), filename="AGENTS.md"):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            for name in directories:
                (root / name).mkdir(parents=True, exist_ok=True)
            for name in files:
                target = root / name
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(b"content")
            source = root / filename
            source.parent.mkdir(parents=True, exist_ok=True)
            source.write_text(text, encoding="utf-8")
            return [f.line for f in analyze(root).findings if f.code == "dead-path"]

    def test_quoted_trailing_slash_directories_are_checked_across_formats(self):
        for filename in FORMATS:
            with self.subTest(filename=filename):
                self.assertEqual(self.scan("CLI: `pnpm11/`.\nSource: `packages/vitest/src/runtime/`.\n",
                                           filename=filename), [1, 2])
                self.assertEqual(self.scan("CLI: `pnpm11/`.\n", directories=("pnpm11",), filename=filename), [])

    def test_regular_file_cannot_satisfy_directory_reference(self):
        self.assertEqual(self.scan("CLI: `pnpm11/`.\n", files=("pnpm11",)), [1])

    def test_directory_does_not_use_ambiguous_suffix_fallback(self):
        self.assertEqual(self.scan("Source: `src/`.\n", directories=("packages/client/src",)), [1])

    def test_explicit_and_nested_directory_bases(self):
        self.assertEqual(self.scan("Read `./src/`.\n", filename="packages/client/AGENTS.md",
                                   directories=("packages/client/src",)), [])
        self.assertEqual(self.scan("Read `../src/`.\n", filename="packages/client/docs/AGENTS.md",
                                   directories=("packages/client/src",)), [])

    def test_unquoted_extensionless_branch_and_example_names_remain_out_of_scope(self):
        self.assertEqual(self.scan("Use src/.\nUse `test/unit`.\nBranch: `feature/change/`.\n"
                                   "Remote: `https://host.test/src/`.\nImport `@scope/package/`.\n"
                                   "Example: `src/foo/`.\nOutside: `../../outside/`.\n"), [])

    def test_optional_and_generated_directory_contexts_remain_local(self):
        self.assertEqual(self.scan("Use `dist/` (if exists), then read `src/`.\n"
                                   "`dist/` is generated by `make build`.\n"), [1])


if __name__ == "__main__":
    unittest.main()
